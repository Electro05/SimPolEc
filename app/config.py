# ---- рождаемость от достатка -----------------------------------------------
# Довольство говорит, ЗАКРЫТЫ ЛИ НУЖДЫ, и потому упирается в потолок задолго до
# того, как страна станет богатой: сытый человек без мебели набирает 0.6 и
# больше уже не наберёт, сколько ему ни продавай. Пока рождаемость висела на
# одном довольстве, у неё был ровно тот же потолок — и население переставало
# расти именно там, где рынок упёрся в потребление и заводу отчаянно нужен
# новый едок.
#
# Поэтому поверх довольства встаёт вторая мера — УРОВЕНЬ ЖИЗНИ, у которой
# потолка нет вовсе. Она и превращает демографию в обратную связь для
# промышленника, ради которой всё затевалось:
#
#   заводы догнали спрос → люди живут лучше → рождаемость взлетает → спроса
#   снова не хватает → есть куда строить;
#   заводы не поспевают → уровень жизни валится → рождаемость глохнет → спрос
#   перестаёт убегать, и цеха успевают его нагнать.
