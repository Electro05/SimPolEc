# ----------------------------------------------------------------------------
# Банкротство и субсидии
# ----------------------------------------------------------------------------
# Предприятия работают в долг: зарплаты и сырьё можно оплачивать в минус, пока
# касса владельца не пробила установленный государством порог. Ниже порога дело
# признаётся банкротом, ВСЕ его цеха встают под замок — и сами уже не
# запускаются.
#
# Выйти из банкротства своими силами нельзя намеренно. Иначе получался порочный
# круг, из которого экономика не выбиралась: рынок затоварен, продаж нет, налоги
# платить надо — касса проваливается; через пейдей склад распродаётся, касса
# всплывает, банкротство снимается само, производство запускается на полную — и
# ровно то же самое повторяется. Теперь решение об окончании банкротства
# принимает государство и оно же выбирает, что запускать обратно: всё подряд или
# только то, что работало в плюс.
BANKRUPTCY_LIMIT = -3_000_000.0   # порог по умолчанию, задаётся лидером
BANKRUPTCY_LIMIT_MIN = -500_000_000.0
# Банкротом дело признаётся не когда касса пробила порог (этого не случается:
# закупки сами ужимаются до остатка и касса лишь подползает к порогу сверху),
# а когда кредита почти не осталось — вот эта доля от порога.
BANKRUPTCY_TRIGGER_MARGIN = 0.02
# Насколько выше порога должна подняться касса, чтобы государство вообще могло
