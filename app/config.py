# ---- офицеры и качество командования ----
# Офицер — не «солдат подороже». Он не прибавляет армии штыков: сколько бы их
# ни было, воюют солдаты. Он прибавляет ей УМЕНИЯ — и на этом держится вся
# разница между армией и вооружённой толпой.
#
# Мера умения — КАЧЕСТВО КОМАНДОВАНИЯ, от 1% до 150%. Считается по фронту, а не
# по стране: офицеры, оставленные в тылу, не командуют никем. На фронте, где
# офицеров хватает по штату (OFFICER_TARGET_SHARE от стоящих там солдат),
# качество выходит на потолок; где их нет вовсе — падает к единице процента.
# Полученная величина прямо умножает боевую силу фронта, поэтому полностью
# укомплектованный офицерами фронт стоит двух с половиной безофицерских.
#
# Платить за это приходится вдвойне. Во-первых, жалованье офицера кратно
# солдатскому. Во-вторых, оно идёт из того же военного бюджета: каждый офицер —
# это несколько несодержанных солдат, и лидеру приходится выбирать между числом
# и умением.
OFFICER_PAY_MULT = 4.0           # во сколько раз офицер дороже солдата ПО УМОЛЧАНИЮ
OFFICER_TARGET_SHARE = 0.05      # офицеров на солдата для полного качества
OFFICER_RECRUIT_SHARE = 0.030    # какую долю сословия забирает набор за пейдей
OFFICER_DISCHARGE_SHARE = 0.060  # скорость роспуска лишних офицеров

